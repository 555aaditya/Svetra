fn temp_project(name: &str, yaml: &str) -> std::path::PathBuf {
    let dir = std::env::temp_dir().join(format!("svetra-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("svetra.yaml"), yaml).unwrap();
    dir
}

#[test]
fn compile_writes_every_file_with_header_and_check_passes() {
    let dir = temp_project("compile", include_str!("fixtures/finledger.yaml"));
    let file = dir.join("svetra.yaml");
    let out = svetra(&["compile", file.to_str().unwrap()]);
    assert_eq!(
        out.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&out.stdout)
    );
    let sql = std::fs::read_to_string(dir.join("supabase/schemas/svetra.sql")).unwrap();
    let ts = std::fs::read_to_string(dir.join("src/svetra.gen.ts")).unwrap();
    let tests = std::fs::read_to_string(dir.join("supabase/tests/svetra.test.sql")).unwrap();
    assert!(
        tests.starts_with("-- Generated by svetra ")
            && tests.ends_with(include_str!("golden/finledger.test.sql"))
    );
    assert!(
        sql.starts_with("-- Generated by svetra ") && sql.contains("Do not edit.\n\n-- Tables\n")
    );
    assert!(sql.ends_with(include_str!("golden/finledger.sql")));
    assert!(
        ts.starts_with("// Generated by svetra ")
            && ts.ends_with(include_str!("golden/finledger.ts"))
    );
    let check = svetra(&["compile", file.to_str().unwrap(), "--check"]);
    assert_eq!(check.status.code(), Some(0));
}

#[test]
fn compile_check_catches_hand_edits_and_stale_files() {
    let dir = temp_project("stale", include_str!("fixtures/finledger.yaml"));
    let file = dir.join("svetra.yaml");
    svetra(&["compile", file.to_str().unwrap()]);
    std::fs::write(dir.join("src/svetra.gen.ts"), "// edited by hand\n").unwrap();
    let out = svetra(&["compile", file.to_str().unwrap(), "--check"]);
    assert_eq!(out.status.code(), Some(1));
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(stdout.contains("out of date: src/svetra.gen.ts"));
    assert!(!stdout.contains("out of date: supabase/schemas/svetra.sql"));
    // Changing the graph makes both files stale: the revision in the header changes.
    let changed =
        include_str!("fixtures/finledger.yaml").replace("system: FinLedger", "system: Ledger");
    std::fs::write(&file, changed).unwrap();
    svetra(&["compile", file.to_str().unwrap()]);
    let sql = std::fs::read_to_string(dir.join("supabase/schemas/svetra.sql")).unwrap();
    std::fs::write(&file, include_str!("fixtures/finledger.yaml")).unwrap();
    let out = svetra(&["compile", file.to_str().unwrap(), "--check"]);
    assert_eq!(out.status.code(), Some(1));
    assert!(
        String::from_utf8_lossy(&out.stdout).contains("out of date: supabase/schemas/svetra.sql")
    );
    assert!(sql.contains("revision"));
}

